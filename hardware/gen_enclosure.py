#!/usr/bin/env python3
"""Generate a 3D-printable enclosure (OpenSCAD) for the DrumDuino carrier board.

Every hole position is read from drumduino-carrier/drumduino-carrier.kicad_pcb, so the box follows the board.
The box splits at the height of the jack centres: each round jack hole is half in the base and half in the lid,
so the board (with jacks soldered on) simply drops into the base. Four M3 screws go up through the base standoffs,
the board's mounting holes, and into posts in the lid, which clamps everything together.

Run: python3 gen_enclosure.py   -> enclosure/drumduino-enclosure.scad (+ STL/PNG via openscad)
"""
import os, math, subprocess
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.join(HERE, 'drumduino-carrier', 'drumduino-carrier.kicad_pcb')
OUT = os.path.join(HERE, 'enclosure')
os.makedirs(OUT, exist_ok=True)

b = pcbnew.LoadBoard(PCB)
bb = b.GetBoardEdgesBoundingBox()
W, H = round(pcbnew.ToMM(bb.GetWidth()) - 0.1, 3), round(pcbnew.ToMM(bb.GetHeight()) - 0.1, 3)   # bbox includes the 0.1 mm outline stroke

def fp_point(fp, px, py):
    """footprint-local point (mm, KiCad axes) -> board mm"""
    t = math.radians(fp.GetOrientationDegrees())
    o = fp.GetPosition()
    x = px * math.cos(t) + py * math.sin(t)
    y = -px * math.sin(t) + py * math.cos(t)
    return pcbnew.ToMM(o.x) + x, pcbnew.ToMM(o.y) + y

top_jacks, bot_jacks, holes, labels = [], [], [], {}
for fp in b.GetFootprints():
    ref = fp.GetReference()
    if fp.GetFPID().GetLibItemName() == 'Jack_6.35mm_Neutrik_NRJ6HF_Horizontal':
        x, y = fp_point(fp, 20.0, 7.23)          # a point on the nose axis, outside the board
        val = fp.GetValue()
        name = val.split(' ', 2)[2] if val.startswith('IN ') else 'PEDAL'
        ch = val.split(' ')[1] if val.startswith('IN ') else 'A15'
        (top_jacks if y < H / 2 else bot_jacks).append((round(x, 3), ch, name))
    elif ref == 'J17':
        dc_y = pcbnew.ToMM([p for p in fp.Pads() if p.GetNumber() == '1'][0].GetPosition().y)
    elif ref.startswith('H'):
        p = fp.GetPosition()
        holes.append((round(pcbnew.ToMM(p.x), 3), round(pcbnew.ToMM(p.y), 3)))
    elif ref == 'U1':
        u = fp.GetPosition()
        usb_y = pcbnew.ToMM(u.y) + 2.5             # centre of the micro-USB in the module model (estimate)
top_jacks.sort(); bot_jacks.sort()

def scad_list(items):
    return '[' + ', '.join(items) + ']'

scad = f'''// DrumDuino enclosure — generated by gen_enclosure.py from the KiCad board. Units: mm.
// Board frame: X = board x, Y = board height - board y (so it reads the same as the PCB seen from above).
// Print: base with the floor on the bed; lid upside down (top on the bed). PLA/PETG, 0.2 mm layers, no supports needed.
$fn = 64;

/* [Measure these on your real parts and adjust] */
jack_axis_h = 6.3;    // jack nose centre above the PCB top
dc_axis_h   = 6.5;    // DC jack opening centre above the PCB top
usb_axis_h  = 9.6;    // micro-USB centre above the carrier PCB top (it is under the Mega PRO)
jack_hole_d = 10.0;   // 3/8" thread
dc_hole_d   = 10.0;
usb_w = 14; usb_h = 10;

/* [Box] */
wall = 2.4; floor_t = 2.4; top_t = 2.0;
gap = 0.4;            // board edge to inner wall
standoff_h = 5;       // board bottom above the floor
pcb_t = 1.6;
inner_h = 26;         // floor to lid inside (Mega PRO stack is about 16 mm above the PCB)
post_d = 7;
screw_clear_d = 3.4;  // M3 clearance through the base
screw_pilot_d = 2.6;  // M3 thread-forming into the lid posts (use 2.5–2.7 for PLA)

W = {W:.3f}; H = {H:.3f};
pcb_top = standoff_h + pcb_t;
split_z = pcb_top + jack_axis_h;
top_jacks = {scad_list('[%.3f, "%s", "%s"]' % j for j in top_jacks)};
bot_jacks = {scad_list('[%.3f, "%s", "%s"]' % j for j in bot_jacks)};
mount = {scad_list('[%.3f, %.3f]' % (x, H - y) for x, y in holes)};
dc_y  = {H - dc_y:.3f};
usb_y = {H - usb_y:.3f};

ox0 = -gap - wall; oy0 = -gap - wall;
OW = W + 2 * (gap + wall); OH = H + 2 * (gap + wall);
OZ0 = -floor_t; OZ1 = inner_h + top_t;

module rbox(x, y, z, w, h, d, r = 3) {{
  translate([x, y, z]) hull() for (i = [r, w - r], j = [r, h - r]) translate([i, j, 0]) cylinder(r = r, h = d);
}}
module shell() {{
  difference() {{
    rbox(ox0, oy0, OZ0, OW, OH, OZ1 - OZ0, 3);
    rbox(-gap, -gap, 0, W + 2 * gap, H + 2 * gap, inner_h, 1);
  }}
}}
module openings() {{
  for (j = top_jacks) translate([j[0], H + gap - 1, split_z]) rotate([-90, 0, 0]) cylinder(d = jack_hole_d, h = wall + 2);
  for (j = bot_jacks) translate([j[0], -gap + 1, split_z]) rotate([90, 0, 0]) cylinder(d = jack_hole_d, h = wall + 2);
  translate([W + gap - 1, dc_y, pcb_top + dc_axis_h]) rotate([0, 90, 0]) cylinder(d = dc_hole_d, h = wall + 2);
  translate([-gap - wall - 1, usb_y - usb_w / 2, pcb_top + usb_axis_h - usb_h / 2]) cube([wall + 2, usb_w, usb_h]);
}}
module labels() {{
  d = 0.6;
  for (j = top_jacks) translate([j[0], H - 4.5, OZ1 - d]) {{
    translate([0, 0, 0]) linear_extrude(d + 0.1) text(j[1], size = 3.4, halign = "center", valign = "center", font = "DejaVu Sans:style=Bold");
    translate([0, -5.2, 0]) linear_extrude(d + 0.1) text(j[2], size = 2.4, halign = "center", valign = "center", font = "DejaVu Sans");
  }}
  for (j = bot_jacks) translate([j[0], 4.5, OZ1 - d]) {{
    linear_extrude(d + 0.1) text(j[1], size = 3.4, halign = "center", valign = "center", font = "DejaVu Sans:style=Bold");
    translate([0, 5.2, 0]) linear_extrude(d + 0.1) text(j[2], size = 2.4, halign = "center", valign = "center", font = "DejaVu Sans");
  }}
  translate([W / 2 + 12, H / 2, OZ1 - d]) linear_extrude(d + 0.1) text("DrumDuino", size = 9, halign = "center", valign = "center", font = "DejaVu Sans:style=Bold");
  translate([W - 9, dc_y - 9, OZ1 - d]) linear_extrude(d + 0.1) text("DC 9V", size = 3, halign = "center", valign = "center", font = "DejaVu Sans:style=Bold");
  translate([8, usb_y + 10, OZ1 - d]) linear_extrude(d + 0.1) text("USB", size = 3, halign = "center", valign = "center", font = "DejaVu Sans:style=Bold");
}}
module base() {{
  difference() {{
    union() {{
      intersection() {{ shell(); translate([ox0 - 1, oy0 - 1, OZ0 - 1]) cube([OW + 2, OH + 2, split_z - OZ0 + 1]); }}
      for (m = mount) translate([m[0], m[1], 0]) cylinder(d = post_d, h = standoff_h);
    }}
    openings();
    for (m = mount) translate([m[0], m[1], OZ0 - 1]) cylinder(d = screw_clear_d, h = standoff_h - OZ0 + 2);
  }}
}}
module lid() {{
  difference() {{
    union() {{
      intersection() {{ shell(); translate([ox0 - 1, oy0 - 1, split_z]) cube([OW + 2, OH + 2, OZ1 - split_z + 1]); }}
      for (m = mount) translate([m[0], m[1], pcb_top]) cylinder(d = post_d, h = inner_h - pcb_top + 0.01);
    }}
    openings();
    labels();
    for (m = mount) translate([m[0], m[1], pcb_top - 1]) cylinder(d = screw_pilot_d, h = inner_h - pcb_top - 1);
  }}
}}

part = "both";   // "base", "lid", "both" (exploded preview)
if (part == "base") base();
else if (part == "lid_assembled") lid();
else if (part == "lid") translate([0, 0, OZ1]) rotate([180, 0, 0]) translate([0, 0, 0]) mirror([0, 0, 0]) lid();
else {{ color("#2d6cdf") base(); color("#e8e8e8", 0.85) translate([0, 0, 25]) lid(); }}
'''
open(os.path.join(OUT, 'drumduino-enclosure.scad'), 'w').write(scad)
print('W', W, 'H', H, 'top', len(top_jacks), 'bot', len(bot_jacks), 'holes', holes, 'dc_y', dc_y, 'usb_y', usb_y)
